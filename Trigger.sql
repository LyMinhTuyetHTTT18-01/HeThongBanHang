--Khôi phục tồn kho nếu xóa chi tiết đơn hàng
CREATE TRIGGER T_KhoiPhuc_TonKho_AfterDelete
ON CHITIETDONHANG
AFTER DELETE
AS
BEGIN
UPDATE SANPHAM
SET SoLuongTonKho = SoLuongTonKho + d.SoLuong
FROM SANPHAM SP
JOIN deleted d ON SP.MaSP = d.MaSP;
END;
GO

