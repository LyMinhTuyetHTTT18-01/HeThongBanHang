--Tự động cập nhật tồn kho sau khi thêm chi tiết đơn hàng
CREATE TRIGGER T_Giam_TonKho_AfterInsert
ON CHITIETDONHANG
AFTER INSERT
AS
BEGIN
UPDATE SANPHAM
SET SoLuongTonKho = SoLuongTonKho - i.SoLuong
FROM SANPHAM SP
JOIN inserted i ON SP.MaSP = i.MaSP;
END;
GO

